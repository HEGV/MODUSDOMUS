const languageButtons = document.querySelectorAll('.lang');
function setLanguage(lang) {
  MD.applyLanguage(lang, translations, 'data-i18n');
}
languageButtons.forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
setLanguage(MD.getLanguage());
document.getElementById('year').textContent = new Date().getFullYear();

const menuButton = document.querySelector('.menu-toggle');
const navigation = document.querySelector('.main-nav');
function setMenu(open, returnFocus = false) {
  navigation.classList.toggle('open', open);
  menuButton.setAttribute('aria-expanded', String(open));
  menuButton.dataset.uiLabel = open ? 'menuClose' : 'menuOpen';
  menuButton.setAttribute('aria-label', MD.ui[document.documentElement.lang][menuButton.dataset.uiLabel]);
  if (returnFocus) menuButton.focus();
}
menuButton.addEventListener('click', () => setMenu(menuButton.getAttribute('aria-expanded') !== 'true'));
navigation.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
  setMenu(false);
  const target = document.querySelector(link.getAttribute('href'));
  if (target) {
    target.setAttribute('tabindex', '-1');
    target.focus({ preventScroll: true });
    target.addEventListener('blur', () => target.removeAttribute('tabindex'), { once: true });
  }
}));
document.addEventListener('keydown', event => {
  if (event.key === 'Escape' && navigation.classList.contains('open')) setMenu(false, true);
});
document.addEventListener('click', event => {
  if (!event.target.closest('.site-header')) setMenu(false);
});
document.addEventListener('focusin', event => {
  if (!event.target.closest('.site-header')) setMenu(false);
});
window.addEventListener('resize', () => {
  if (window.matchMedia('(min-width: 1201px)').matches) setMenu(false);
}, { passive: true });

// Decorative tap feedback. Scrolling is never prevented or intercepted.
document.querySelectorAll('.process-grid > div').forEach(card => {
  let start = null;
  let resetTimer;
  card.addEventListener('pointerdown', event => {
    if (event.pointerType === 'mouse' || !event.isPrimary) return;
    start = { x: event.clientX, y: event.clientY, id: event.pointerId };
  }, { passive: true });
  card.addEventListener('pointermove', event => {
    if (start && (Math.abs(event.clientX - start.x) > 10 || Math.abs(event.clientY - start.y) > 10)) start = null;
  }, { passive: true });
  card.addEventListener('pointercancel', () => { start = null; }, { passive: true });
  card.addEventListener('pointerup', event => {
    if (!start || event.pointerId !== start.id) return;
    start = null;
    clearTimeout(resetTimer);
    card.classList.add('is-tapped');
    resetTimer = setTimeout(() => card.classList.remove('is-tapped'), 650);
  }, { passive: true });
});
